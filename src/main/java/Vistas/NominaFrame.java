    private void btnPagarNominaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagarNominaActionPerformed
        // TODO add your handling code here:

        int filaSeleccionada = tblNomina.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione una nómina de la tabla."
            );
            return;
        }

        // Obtener código de nómina
        int codigoNomina = Integer.parseInt(tblNomina.getValueAt(filaSeleccionada,0).toString());
        // Obtener estado
        String estado = tblNomina.getValueAt(filaSeleccionada,5).toString();

        // Verificar que esté pendiente
        if (!estado.equals("PENDIENTE")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Esta nómina ya fue pagada."
            );

            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(
                        this,
                        "¿Desea pagar esta nómina?",
                        "Confirmar pago",
                        JOptionPane.YES_NO_OPTION
                );

        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        NominaDAO dao = new NominaDAO();
        boolean pagada = dao.pagarNomina(codigoNomina);

        if (pagada) {

            JOptionPane.showMessageDialog(
                    this,
                    "Nómina pagada correctamente."
            );

            cargarTabla();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo pagar la nómina."
            );
        }
    }//GEN-LAST:event_btnPagarNominaActionPerformed

