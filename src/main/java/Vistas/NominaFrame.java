    private void btnGenerarNominaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarNominaActionPerformed
        // TODO add your handling code here:

        // Verificar empleado
        if (cmbEmpleado.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un empleado."
            );

            return;
        }
        
        String dpi = cmbEmpleado.getSelectedItem().toString();

        String tipoPago = cmbTipoPago.getSelectedItem().toString();
        
        java.time.LocalDate fecha  = java.time.LocalDate.now();
        java.sql.Date fechaSQL = java.sql.Date.valueOf(fecha);
        NominaDAO dao = new NominaDAO();

        // Verificar que no exista
        if (dao.existeNomina(
                dpi,
                fechaSQL,
                tipoPago)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ya existe una nómina de este tipo para este empleado en esta fecha."
            );

            return;
        }

        // Obtener salario
        double salario = dao.obtenerSalario(dpi);

        if (salario <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo obtener el salario del empleado."
            );

            return;
        }

        // Calcular porcentaje
        double porcentaje;

        if (tipoPago.equals("QUINCENA")) {

            porcentaje = 0.30;

        } else {

            porcentaje = 0.70;
        }

        // Calcular monto
        double monto = salario * porcentaje;

        // Mostrar datos
        txtFechaEmision.setText(
                fecha.toString()
        );

        txtMonto.setText(
                String.format("%.2f", monto)
        );

        cmbEstado.setSelectedItem("PENDIENTE");

        // Confirmar
        int confirmar
                = JOptionPane.showConfirmDialog(
                        this,
                        "Empleado: " + dpi
                        + "\nTipo de pago: " + tipoPago
                        + "\nSalario: Q"
                        + String.format("%.2f", salario)
                        + "\nMonto a pagar: Q"
                        + String.format("%.2f", monto)
                        + "\n\n¿Desea generar esta nómina?",
                        "Confirmar nómina",
                        JOptionPane.YES_NO_OPTION
                );

        if (confirmar != JOptionPane.YES_OPTION) {

            return;
        }

        // Registrar
        boolean registrada
                = dao.registrarNomina(
                        dpi,
                        fechaSQL,
                        tipoPago,
                        monto
                );

        if (registrada) {

            JOptionPane.showMessageDialog(
                    this,
                    "Nómina generada correctamente."
            );

            cargarTabla();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo generar la nómina."
            );
        }
    }//GEN-LAST:event_btnGenerarNominaActionPerformed


