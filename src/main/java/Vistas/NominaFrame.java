    private void cargarTabla() {

        DefaultTableModel modelo = (DefaultTableModel) tblNomina.getModel();

        // Limpiar la tabla
        modelo.setRowCount(0);

        NominaDAO dao = new NominaDAO();
        try {

            ResultSet resultado = dao.consultarNominas();

            while (resultado.next()) {
                modelo.addRow(
                        new Object[]{
                            resultado.getInt("codigo_nomina"),
                            resultado.getString("dpi_empleado"),
                            resultado.getDate("fecha_emision"),
                            resultado.getString("tipo_de_pago"),
                            resultado.getDouble("monto"),
                            resultado.getString("estado_pago")
                        }
                );
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error al cargar las nóminas."
            );

            e.printStackTrace();
        }
    }

    private void cargarCombos() {
        // Empleados activos
        cmbEmpleado.removeAllItems();

        NominaDAO dao = new NominaDAO();

        try {

            ResultSet resultado = dao.consultarEmpleadosActivos();

            while (resultado.next()) {

                String dpi = resultado.getString("dpi");

                cmbEmpleado.addItem(dpi);
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al cargar los empleados."
            );

            e.printStackTrace();
        }

        // Tipo de pago
        cmbTipoPago.removeAllItems();

        cmbTipoPago.addItem("QUINCENA");
        cmbTipoPago.addItem("FIN_DE_MES");

        // Estado
        cmbEstado.removeAllItems();

        cmbEstado.addItem("PENDIENTE");

        // Seleccionamos PENDIENTE
        cmbEstado.setSelectedItem("PENDIENTE");

        // El estado no lo modifica el usuario
        cmbEstado.setEnabled(false);

        // El monto lo calcula el sistema
        txtMonto.setEditable(false);

        // La fecha la coloca el sistema
        txtFechaEmision.setEditable(false);

        // Colocar fecha actual
        txtFechaEmision.setText(
                java.time.LocalDate.now().toString()
        );
    }
